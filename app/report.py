from app.domain import ResearchReport
class Writer:
 def write(self,goal,claims,evidence,contradictions,critique):
  limitations=[]
  if contradictions:limitations.append("Conflicting evidence requires human review.")
  if critique.get("unsupported_claims"):limitations.append("Some claims lack sufficient evidence.")
  summary="Research completed with evidence-linked claims. In production, synthesis is generated by the configured writer model using only authorized evidence."
  return ResearchReport(title=goal,summary=summary,claims=claims,citations={e.id:e for e in evidence},limitations=limitations)
